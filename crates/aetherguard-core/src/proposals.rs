/* Authorized Protocol Quality Assurance & Formal Verification Engine */

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// Parameters describing a decentralized exchange (DEX) swap operation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct SwapParameters {
    /// Inbound asset traded (e.g. "USDC")
    pub asset_in: String,
    /// Outbound asset requested (e.g. "XLM")
    pub asset_out: String,
    /// Exact atomic input amount
    pub amount_in: u128,
    /// Fair expected output amount based on reference pool/quote
    pub expected_amount_out: u128,
    /// Minimum acceptable output amount specified on-chain
    pub min_amount_out: u128,
    /// Optional oracle reference price in basis points (scaled by 10,000)
    pub oracle_reference_price_bps: Option<u64>,
}

/// Represents an untrusted, proposed transaction generated by an Autonomous AI Agent.
/// The agent acts strictly as a PROPOSER. It has zero authority to sign or execute.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct AgentTransactionProposal {
    pub proposal_id: String,
    pub agent_id: String,
    /// Hash of the natural-language prompt or LLM reasoning turn that induced this action
    pub intent_prompt_hash: String,
    pub target_contract: String,
    pub function_name: String,
    pub recipient: String,
    pub amount: u128,
    pub asset_symbol: String,
    /// Optional DEX swap parameters for slippage & oracle invariant verification
    pub swap_params: Option<SwapParameters>,
    /// Unix timestamp in seconds
    pub timestamp: i64,
}

impl AgentTransactionProposal {
    pub fn new(
        agent_id: impl Into<String>,
        prompt_text: &str,
        target_contract: impl Into<String>,
        function_name: impl Into<String>,
        recipient: impl Into<String>,
        amount: u128,
        asset_symbol: impl Into<String>,
        timestamp: i64,
    ) -> Self {
        let mut hasher = Sha256::new();
        hasher.update(prompt_text.as_bytes());
        let intent_prompt_hash = hex::encode(hasher.finalize());

        let agent_id_s = agent_id.into();
        let target_contract_s = target_contract.into();
        let recipient_s = recipient.into();

        // Unique deterministic proposal identifier
        let mut id_hasher = Sha256::new();
        id_hasher.update(agent_id_s.as_bytes());
        id_hasher.update(amount.to_be_bytes());
        id_hasher.update(recipient_s.as_bytes());
        id_hasher.update(timestamp.to_be_bytes());
        let proposal_id = format!("prop_{}", &hex::encode(id_hasher.finalize())[..16]);

        Self {
            proposal_id,
            agent_id: agent_id_s,
            intent_prompt_hash,
            target_contract: target_contract_s,
            function_name: function_name.into(),
            recipient: recipient_s,
            amount,
            asset_symbol: asset_symbol.into(),
            swap_params: None,
            timestamp,
        }
    }

    pub fn with_swap_params(mut self, params: SwapParameters) -> Self {
        self.swap_params = Some(params);
        self
    }

    /// Compute canonical digest of the proposal for cryptographic invariant attestation
    pub fn digest(&self) -> [u8; 32] {
        let mut hasher = Sha256::new();
        hasher.update(self.proposal_id.as_bytes());
        hasher.update(self.agent_id.as_bytes());
        hasher.update(self.intent_prompt_hash.as_bytes());
        hasher.update(self.target_contract.as_bytes());
        hasher.update(self.function_name.as_bytes());
        hasher.update(self.recipient.as_bytes());
        hasher.update(self.amount.to_be_bytes());
        hasher.update(self.asset_symbol.as_bytes());
        if let Some(ref swap) = self.swap_params {
            hasher.update(swap.asset_in.as_bytes());
            hasher.update(swap.asset_out.as_bytes());
            hasher.update(swap.amount_in.to_be_bytes());
            hasher.update(swap.expected_amount_out.to_be_bytes());
            hasher.update(swap.min_amount_out.to_be_bytes());
            if let Some(oracle_price) = swap.oracle_reference_price_bps {
                hasher.update(oracle_price.to_be_bytes());
            }
        }
        hasher.update(self.timestamp.to_be_bytes());
        hasher.finalize().into()
    }
}
